import { useMemo, useState } from 'react';
import { Link as RouterLink } from 'react-router-dom';
import { Box, Button, Link } from '@mui/material';
import DownloadIcon from '@mui/icons-material/Download';
import DescriptionIcon from '@mui/icons-material/Description';
import dayjs from 'dayjs';
import { PageHeader, DataTable, EmptyState, ErrorAlert } from '../../../components/ui';
import { useGetLabReportsQuery } from '../api';
import type { LabReport } from '../types';
import { patientLabel, userName } from '../types';

export default function LabReports() {
  const [page, setPage] = useState(1);
  const [pageSize, setPageSize] = useState(20);
  const { data, isLoading, isFetching, error } = useGetLabReportsQuery({ page_size: pageSize });

  const columns = useMemo(
    () => [
      { key: 'id', label: '#', render: (r: LabReport) => <strong>R-{r.id}</strong> },
      {
        key: 'order',
        label: 'Order',
        render: (r: LabReport) => (
          <Link component={RouterLink} to={`/laboratory/orders/${typeof r.order === 'number' ? r.order : r.order.id}`} underline="hover">
            L-{typeof r.order === 'number' ? r.order : r.order.id}
          </Link>
        ),
      },
      {
        key: 'patient',
        label: 'Patient',
        render: (r: LabReport) =>
          typeof r.order === 'object' && r.order ? patientLabel(r.order.patient) : '—',
      },
      { key: 'generated_by', label: 'Generated by', render: (r: LabReport) => userName(r.generated_by) },
      { key: 'generated_at', label: 'Generated', render: (r: LabReport) => dayjs(r.generated_at).format('DD MMM YYYY HH:mm') },
      {
        key: 'actions',
        label: '',
        render: (r: LabReport) => (
          <Button
            size="small"
            variant="outlined"
            startIcon={<DownloadIcon />}
            component="a"
            href={r.file}
            target="_blank"
            rel="noreferrer"
          >
            PDF
          </Button>
        ),
      },
    ],
    [],
  );

  if (error) return <ErrorAlert error={error} />;

  return (
    <Box>
      <PageHeader title="Lab reports" subtitle="Generated PDF reports" />
      <DataTable
        columns={columns}
        rows={data?.results ?? []}
        loading={isLoading || isFetching}
        rowKey={(r) => String(r.id)}
        page={page}
        pageSize={pageSize}
        count={data?.count ?? 0}
        onPageChange={setPage}
        onPageSizeChange={(s: number) => { setPageSize(s); setPage(1); }}
        emptyState={<EmptyState icon={<DescriptionIcon />} title="No reports yet" hint="Reports are generated when lab orders are completed." />}
      />
    </Box>
  );
}
